/**
 * 全來源寵物名正規化（別名 → 正式名）。
 *
 * 收的是「攻略原文的寫法」對「專屬寵物.csv 正式名」——
 * CSV 本身存正式名，別名只會從手寫樹、公告文字這類內容側進來。
 */
const ALIASES: Record<string, string> = {
  /** 舊檔名／錯字：毆 → 歐 */
  毆茲那克: '歐茲那克',
  /** 公告偶發把「那克」寫成「尼克」（熊弟線） */
  酒仙歐茲尼克: '酒仙歐茲那克',
  羅剎歐茲尼克: '羅剎歐茲那克',
  /** 軍方研究所攻略原文寫「赤焰黃蜂」，專屬寵物表正式名「赤炎黃蜂」 */
  赤焰黃蜂: '赤炎黃蜂',
  /**
   * 魔力豆知識攻略寫「兔耳嚇人箱(改造陰影)」，產物正式名「改造陰影」。
   * 注意純「兔耳嚇人箱」不是別名——那是改造陰影的底寵本人。
   */
  '兔耳嚇人箱(改造陰影)': '改造陰影',
};

export function normalizePetName(name: string): string {
  const n = (name ?? '').trim();
  if (!n) return n;
  return ALIASES[n] ?? n;
}
